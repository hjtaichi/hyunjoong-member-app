export function normalizeShopCategory(value) {
  const raw = String(value || "").trim();

  if (!raw) {
    return "기타";
  }

  if (SHOP_CATEGORY_KEYS.includes(raw)) {
    return raw;
  }

  return CATEGORY_ALIASES[raw] || "기타";
}
